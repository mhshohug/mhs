    weather.temperatureC !== null ? ` · ${toBengaliDigits(weather.temperatureC)}°C` : '';
  const skyLabel = `আজকের আকাশ ও পরিবেশ · ${weather.descriptionBn}${tempText}`;

  const isEid = checkIsEidToday(new Date());
